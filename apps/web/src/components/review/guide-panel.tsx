"use client"

import type { GuideState } from "@docks/api"
import { useMutation, useQueryClient } from "@tanstack/react-query"
import { IconRefresh, IconSparkles } from "@tabler/icons-react"
import { useState } from "react"

import { Button } from "@/components/ui/button"
import { Skeleton } from "@/components/ui/skeleton"
import { cn } from "@/lib/utils"
import { useTRPC } from "@/trpc/react"

/** Summary and numbered tour steps; clicking a step filters the diff (§5.3). */
export function GuidePanel({
  repo,
  number,
  state,
  activeStep,
  onStepChange,
  canAct = true,
}: {
  repo: string
  number: number
  state: GuideState | undefined
  activeStep: number | null
  onStepChange: (step: number | null) => void
  canAct?: boolean
}) {
  const trpc = useTRPC()
  const queryClient = useQueryClient()
  const [error, setError] = useState<string>()
  const regenerate = useMutation(
    trpc.review.regenerateGuide.mutationOptions({
      onSuccess: (next) => {
        setError(undefined)
        onStepChange(null)
        queryClient.setQueryData(trpc.review.guide.queryKey({ repo, number }), next)
      },
      onError: (e) => setError(e.message),
    })
  )

  if (!state || state.status === "pending") {
    return (
      <section className="space-y-2 bg-card border-hairline rounded-xl border p-4" aria-busy="true">
        <p className="text-muted-foreground flex items-center gap-2 text-sm">
          <IconSparkles className="size-4" aria-hidden />
          Building the review guide…
        </p>
        <Skeleton className="h-4 w-3/4" />
        <Skeleton className="h-4 w-1/2" />
      </section>
    )
  }

  const { guide } = state
  const ai = guide.source === "ai"

  return (
    <section className="space-y-3 bg-card border-hairline rounded-xl border p-4">
      <div className="flex items-start gap-2">
        <p className="flex-1 text-sm">
          {ai && <IconSparkles className="text-muted-foreground mr-1.5 inline size-4" aria-label="AI summary" />}
          {guide.summary}
        </p>
        {ai && canAct && (
          <Button
            size="sm"
            variant="ghost"
            disabled={regenerate.isPending}
            onClick={() => regenerate.mutate({ repo, number })}
          >
            <IconRefresh className="size-4" aria-hidden />
            Regenerate
          </Button>
        )}
      </div>
      {error && <p className="text-destructive text-sm">{error}</p>}

      {guide.steps.length > 0 && (
        <ol className="grid auto-rows-fr gap-2 sm:grid-cols-2">
          <li className="h-full">
            <button
              type="button"
              onClick={() => onStepChange(null)}
              className={cn(
                "hover:bg-hover/50 border-hairline flex h-full w-full flex-col justify-center rounded-lg border px-3 py-2.5 text-left text-sm transition-colors",
                activeStep === null && "bg-raised border-transparent shadow-(--ring-raised)"
              )}
            >
              <span className="font-medium">All files</span>
              <span className="text-muted-foreground mt-0.5 block text-xs">Show the full diff.</span>
            </button>
          </li>
          {guide.steps.map((step, i) => (
            <li key={i} className="h-full">
              <button
                type="button"
                onClick={() => onStepChange(activeStep === i ? null : i)}
                aria-pressed={activeStep === i}
                className={cn(
                  "hover:bg-hover/50 border-hairline flex h-full w-full flex-col justify-center rounded-lg border px-3 py-2.5 text-left text-sm transition-colors",
                  activeStep === i && "bg-raised border-transparent shadow-(--ring-raised)"
                )}
              >
                <span className="font-medium">
                  {i + 1}. {step.title}
                </span>
                <span className="text-muted-foreground ml-1 text-xs">
                  {step.files.length} file{step.files.length === 1 ? "" : "s"}
                </span>
                {step.why && <span className="text-muted-foreground mt-0.5 block text-xs">{step.why}</span>}
              </button>
            </li>
          ))}
        </ol>
      )}
      {ai && state.model && (
        <p className="text-muted-foreground text-xs">
          Generated by {state.model}. Check it against the diff; it can miss things.
        </p>
      )}
    </section>
  )
}
